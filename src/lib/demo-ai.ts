/**
 * Stream a demo reply chunk-by-chunk into the UI.
 * Returns false if the stream was aborted early.
 */
export async function streamDemoReply(reply: string, onDelta: (text: string) => void, signal: AbortSignal): Promise<boolean> {
  const tokens = reply.match(/\s*\S+/g) ?? [reply];
  let out = "";
  for (let i = 0; i < tokens.length; i++) {
    if (signal.aborted) return false;
    out += tokens[i];
    // emit every few tokens for a natural typing feel
    if (i % 3 === 0 || i === tokens.length - 1) {
      onDelta(out);
      await new Promise((r) => setTimeout(r, 14));
    }
  }
  return true;
}
